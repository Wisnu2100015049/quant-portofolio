def calculate_momentum(data) :
  """Calculate Momentum using T-12 Month up to T-2 Month Return"""
  data = data.copy()
  data['FactorMomentum'] = data.groupby('Ticker')['PriceClose'].transform(lambda x: (x.shift(2) - x.shift(12)) / x.shift(12))
  return data

