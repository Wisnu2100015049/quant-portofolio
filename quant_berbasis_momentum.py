def run_backtest(stocks_data,
                 start_period,
                 end_period,
                 percentile,
                 buffer_n_year,
                 feature_cols,
                 FEE):

    # 1. Perbaikan Filter Data (Wajib diassign kembali ke variabel)
    stocks_data = stocks_data.copy()
    stocks_data = stocks_data.loc[
        (stocks_data['Date'] >= start_period) &
        (stocks_data['Date'] <= end_period)
    ]

    # Inisialisasi Periode
    initial_buffer_start = pd.to_datetime(start_period)
    initial_buffer_end = initial_buffer_start + pd.DateOffset(years=buffer_n_year) - pd.offsets.MonthEnd(0)
    porto_construction_date = (initial_buffer_end + pd.offsets.MonthEnd(n=1))
    end_time = pd.to_datetime(end_period)

    collection_return = []

    try:
        while porto_construction_date <= end_time:
            print(f'Constructing Portfolio On: {porto_construction_date.date()}')

            # 2. Get Training Data & Scaler
            # Mekanisme: Mengambil data historis dan scaler yang fit pada data tersebut
            X_buffer, y_buffer, current_scaler = get_training_data(
                data=stocks_data,
                initial_buffer_start=initial_buffer_start,
                initial_buffer_end=initial_buffer_end,
                feature_cols=feature_cols
            )

            if X_buffer.empty:
                print('-----Skipping: No training data available')
            else:
                # 3. Training
                model = train_ml_model(X_train=X_buffer, y_train=y_buffer)

                # 4. Construct Portfolio (Melewatkan current_scaler)
                res_porto = construct_portofolio(
                    data=stocks_data,
                    porto_date=porto_construction_date,
                    feature_cols=feature_cols,
                    model=model,
                    scaler=current_scaler, # Penting agar prediksi akurat
                    percentile=percentile
                )

                if not res_porto.empty:
                    print('-----Calculating Return')
                    monthly_net_return = calculate_portofolio_return(return_porto=res_porto, FEE=FEE)

                    porto_return_df = pd.DataFrame({
                        'ReturnDate': [porto_construction_date + pd.offsets.MonthEnd(n=1)],
                        'PortofolioReturn': [monthly_net_return]
                    })
                    collection_return.append(porto_return_df)

            # 5. Shift Periode (Rolling Window Mechanism)
            initial_buffer_start += pd.offsets.MonthEnd(n=1)
            initial_buffer_end += pd.offsets.MonthEnd(n=1)
            porto_construction_date += pd.offsets.MonthEnd(n=1)

    except Exception as e:
        print(f"An error occurred: {e}")

    finally:
        print('Preparing Performance Report')
        if collection_return:
            collection_return_df = pd.concat(collection_return, axis=0).reset_index(drop=True)
            # Menghasilkan laporan akhir
            res_report = report_performance(return_data=collection_return_df)
            return res_report # Mengembalikan data, mean, vol, dan sharpe
        else:
            print("No portfolio returns to calculate.")
            return None

