def calculate_reversal(data):
    """Calculate Reversal using previous month return"""
    data = data.copy()
    # Perubahan: Menambahkan tanda minus (-) di depan untuk mencerminkan logika Reversal
    data['FactorReversal'] = data.groupby('Ticker')['PriceClose'].transform(
        lambda x: -((x.shift(1) - x.shift(2)) / x.shift(2))
    )
    return data

stocks_data = calculate_reversal(data = stocks_data)
