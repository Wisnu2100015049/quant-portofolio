def construct_portofolio(data, porto_date, feature_cols, model, scaler, percentile):
    # 1. Filter data untuk tanggal konstruksi
    y_porto = data[data['Date'] == porto_date].copy()

    if y_porto.empty:
        return pd.DataFrame()

    # 2. Scaling Fitur
    X_porto = scaler.transform(y_porto[feature_cols])

    # 3. Prediksi menggunakan model
    y_porto['Pred Rt+1'] = model.predict(X_porto)

    # --- PERBAIKAN DI SINI: MENGGANTI qcut DENGAN rank ---
    # Mengurutkan prediksi dari yang terkecil ke terbesar
    # pct=True mengubah rank menjadi persentil (0 sampai 1)
    y_porto['rank_pct'] = y_porto['Pred Rt+1'].rank(pct=True, method='first')

    # Pilih saham yang masuk dalam persentil atas
    # Jika percentile 0.1, maka cari yang rank_pct > 0.9
    bound = 1 - percentile
    y_porto['is_porto'] = y_porto['rank_pct'] > bound

    # Ambil hanya yang terpilih
    selected_porto = y_porto[y_porto['is_porto'] == True].copy()

    return selected_porto

