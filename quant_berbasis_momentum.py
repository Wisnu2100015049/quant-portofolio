def calculate_lag_return(data):
    """Calculate Lag Return using previous 6 month return"""
    data = data.copy()
    # Perubahan: Logika shift disesuaikan untuk mengambil return akumulatif 6 bulan,
    # bukan hanya return 1 bulan yang terjadi 6 bulan lalu.
    data['FactorLagReturn-6M'] = data.groupby('Ticker')['PriceClose'].transform(
        lambda x: (x.shift(1) - x.shift(7)) / x.shift(7)
    )
    return data

