def report_performance(return_data):
    return_data = return_data.copy()

    # 1. Menghitung Pertumbuhan Kumulatif
    return_data['PortofolioCumulativeReturn'] = (1 + return_data['PortofolioReturn']).cumprod()

    # 2. Statistik Dasar (Monthly)
    mean_return = return_data['PortofolioReturn'].mean()
    return_volatility = return_data['PortofolioReturn'].std()

    # 3. Perubahan: Menambahkan Annualized Sharpe Ratio
    # (Asumsi Risk-Free Rate = 0, disetahunkan dengan akar 12)
    sharpe_ratio = (mean_return / return_volatility) * (12**0.5) if return_volatility != 0 else 0

    # 4. Perubahan: Menambahkan Total Return Akhir
    total_return = (return_data['PortofolioCumulativeReturn'].iloc[-1] - 1) * 100

    print(f"{'='*30}")
    print(f"PERFORMANCE REPORT")
    print(f"{'='*30}")
    print(f"Total Return          : {total_return:.2f} %")
    print(f"Average Monthly Return : {mean_return*100:.2f} %")
    print(f"Monthly Volatility     : {return_volatility*100:.2f} %")
    print(f"Annualized Sharpe Ratio: {sharpe_ratio:.2f}")
    print(f"{'='*30}")

    return return_data, mean_return, return_volatility, sharpe_ratio

